# Packages the site's pages need, declared where renv can see them.
#
# This file is never sourced. It exists so `renv::snapshot()` records packages
# that are only ever used inside page chunks, and it is the reason it is
# tracked rather than gitignored.
#
# Why it is needed. renv discovers dependencies by parsing code, and it reads
# executable chunks in a .qmd but not the contents of a plain ```r block. Every
# page that still shows code without running it is therefore invisible to that
# scan, and a package used only on such a page silently drops out of the
# lockfile. That is how `terra` came to be missing: it appears three times in
# howdoi/terra.qmd, and `renv::dependencies()` reported it not found.
#
# The failure is quiet and arrives late. Nothing breaks until someone converts
# that page to executing chunks, or restores the project on a clean machine and
# tries to render it, at which point the render dies on `there is no package
# called 'terra'` rather than on anything pointing here.
#
# So: if a page needs a package, name it here. Deleting a line is how a package
# leaves the lockfile, which should be a deliberate act rather than a side
# effect of how a chunk happens to be fenced.

library(terra) # howdoi/terra.qmd: rast(), sources(), inMemory(), gdal()
